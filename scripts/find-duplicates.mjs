import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Editorial rounding tolerances, not validated physical equivalence thresholds.
export const TOLERANCES = Object.freeze({ thickness_mm: 0.01, width_mm: 0.1,
  o2_pct: 0.1, pressure_kpa: 0.1, gravity_g: 0.001,
  flow_speed_cm_s: 0.1, external_heat_flux_kw_m2: 0 });
const requiredNumbers = ['o2_pct', 'pressure_kpa', 'gravity_g', 'flow_speed_cm_s', 'external_heat_flux_kw_m2'];
const requiredText = ['material_id', 'material', 'form', 'flow_direction', 'endpoint'];
const context = ['facility', 'limit_approach', 'pass_criterion', 'test_duration_s'];
const normalize = value => typeof value === 'string' ? value.trim().replace(/\s+/g, ' ').toLowerCase() : value;
const missing = value => value == null || value === '';
const finite = value => typeof value === 'number' && Number.isFinite(value);
const order = (a, b) => a < b ? -1 : a > b ? 1 : 0;

export function findDuplicates(data) {
  if (!Array.isArray(data?.evidence)) throw new Error('Expected S1 evidence array');
  const ids = new Set();
  const rows = [...data.evidence].sort((a, b) => order(a.evidence_id, b.evidence_id));
  const eligible = [], excluded = [], pairs = [];
  for (const row of rows) {
    if (typeof row.evidence_id !== 'string' || !row.evidence_id.trim() || ids.has(row.evidence_id)) {
      throw new Error('Missing or duplicate evidence_id');
    }
    ids.add(row.evidence_id);
    const gaps = requiredText.filter(key => typeof row[key] !== 'string' || !row[key].trim());
    gaps.push(...requiredNumbers.filter(key => !finite(row[key])));
    // Width is structurally inapplicable for rods/wires; unknown geometry elsewhere is excluded.
    if (!finite(row.thickness_mm)) gaps.push('thickness_mm');
    if (!['rod', 'wire'].includes(normalize(row.form)) && !finite(row.width_mm)) gaps.push('width_mm');
    if (missing(normalize(row.outcome)) && !(finite(row.value) && typeof row.value_unit === 'string' && row.value_unit.trim())) gaps.push('result');
    if (gaps.length) excluded.push({ evidence_id: row.evidence_id, fields: gaps });
    else eligible.push(row);
  }
  for (let i = 0; i < eligible.length; i++) {
    for (let j = i + 1; j < eligible.length; j++) {
      const a = eligible[i], b = eligible[j];
      if (requiredText.some(key => normalize(a[key]) !== normalize(b[key]))) continue;
      if (context.some(key => normalize(a[key] ?? null) !== normalize(b[key] ?? null))) continue;
      if (normalize(a.value_unit ?? null) !== normalize(b.value_unit ?? null)) continue;
      const differences = [];
      let matches = true;
      for (const [key, tolerance] of Object.entries(TOLERANCES)) {
        if (missing(a[key]) && missing(b[key])) continue;
        if (!finite(a[key]) || !finite(b[key]) || Math.abs(a[key] - b[key]) > tolerance + 1e-12) {
          matches = false; break;
        }
        if (a[key] !== b[key]) differences.push(key);
      }
      if (!matches) continue;
      const same = normalize(a.outcome ?? null) === normalize(b.outcome ?? null) && (a.value ?? null) === (b.value ?? null);
      pairs.push({ ids: [a.evidence_id, b.evidence_id], kind: same ? 'duplicate' : 'conflict',
        match: differences.length ? 'near' : 'exact', differences,
        unknown_context: context.filter(key => missing(a[key]) || missing(b[key])) });
    }
  }
  return { pairs, excluded, eligible: eligible.length, total: rows.length };
}

const escape = value => String(value).replace(/[\r\n]+/g, ' ').replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('|', '&#124;')
  .replace(/[\\`*_[\]]/g, '\\$&');

export function renderDuplicatesReport(data) {
  const result = findDuplicates(data);
  const byId = new Map(data.evidence.map(row => [row.evidence_id, row]));
  const cite = id => {
    const row = byId.get(id), source = data.sources?.[row.source_key];
    if (!source?.url || !row.source_locator?.trim()) throw new Error(`Missing source or locator: ${id}`);
    const url = new URL(source.url);
    if (!['https:', 'http:'].includes(url.protocol)) throw new Error(`Invalid source: ${id}`);
    return `[${escape(id)}](<${url.href.replaceAll('>', '%3E')}>) (${escape(row.source_locator)}; ${escape(row.review_status ?? 'unknown review status')})`;
  };
  const lines = ['# Duplicate and near-duplicate evidence report', '',
    'Generated by `node scripts/find-duplicates.mjs [input.json] [output.md]`; defaults to `data/evidence.json` and `docs/duplicates-report.md`.', '',
    'Primary dataset context: [NASA PSI Data Repository](https://psi.nasa.gov/). This is an editorial review aid, not an engine label or an assessment of experimental independence. All review statuses are included. No rows are merged, deleted or relabeled.', '',
    'Matching requires the same material ID and source material description (case and whitespace normalized; no synonym or grade merging), form, flow direction, endpoint, result unit and recorded facility/approach/criterion/duration. Numeric conditions must be within these absolute tolerances:', '',
    ...Object.entries(TOLERANCES).map(([key, value]) => `- ${key}: ${value}`), '',
    'Tolerances are editorial choices for rounding, not measured uncertainty or physical equivalence. Exact means identical numeric conditions; near means at least one differs within tolerance. Results are compared exactly: equal outcome and numeric value gives a duplicate candidate; any difference gives a potential conflict requiring source review. Different endpoints or units are not compared. Near conflicts may reflect real condition dependence.', '',
    'Unknown material, endpoint, thickness, atmosphere, gravity, flow or heat flux excludes a row. Width may be absent for rods/wires only. Equal unknown optional context is disclosed below, not treated as established equivalence. Pairwise matches are not transitive groups. Different run IDs can represent independent replication; candidate duplicates do not establish repeated extraction.', '',
    `Inventory: ${result.total} rows; ${result.eligible} eligible; ${result.excluded.length} excluded; ${result.pairs.filter(p => p.kind === 'duplicate').length} duplicate candidates; ${result.pairs.filter(p => p.kind === 'conflict').length} potential conflicts.`, '',
    '## Candidate pairs', '', '| Kind | Match | Evidence and source locators | Differing conditions | Unknown context |', '|---|---|---|---|---|'];
  for (const pair of result.pairs) lines.push(`| ${pair.kind} | ${pair.match} | ${pair.ids.map(cite).join(' / ')} | ${pair.differences.join(', ') || 'none'} | ${pair.unknown_context.join(', ') || 'none'} |`);
  if (!result.pairs.length) lines.push('', 'No candidate pairs found among eligible rows. Excluded rows prevent a conclusion about the complete inventory.');
  lines.push('', '## Excluded rows', '', '| Evidence and source locator | Missing or nonnumeric fields |', '|---|---|');
  for (const row of result.excluded) lines.push(`| ${cite(row.evidence_id)} | ${row.fields.join(', ')} |`);
  return lines.join('\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.length > 4) throw new Error('Usage: node scripts/find-duplicates.mjs [input.json] [output.md]');
    const input = process.argv[2] ?? new URL('../data/evidence.json', import.meta.url);
    const output = process.argv[3] ?? new URL('../docs/duplicates-report.md', import.meta.url);
    await writeFile(output, renderDuplicatesReport(JSON.parse(await readFile(input, 'utf8'))), 'utf8');
  } catch (error) {
    console.error(`Duplicate report failed: ${error.message}`);
    process.exitCode = 1;
  }
}
