import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const IMPORTANT_FIELDS = Object.freeze([
  'uncertainty', 'source_locator', 'pressure_kpa',
  'flow_speed_cm_s', 'flow_direction', 'endpoint',
]);
const blank = (value) => value == null || (typeof value === 'string' && value.trim() === '');
const escape = (value) => String(value).replace(/[\r\n]+/g, ' ').replaceAll('|', '&#124;').replace(/[\\`*_[\]<>]/g, '\\$&');

export function auditMissingFields(data) {
  if (!data || !Array.isArray(data.evidence)) throw new Error('Expected S1 evidence array');
  const sources = new Map();
  const rows = data.evidence.map((row) => {
    if (!row || typeof row !== 'object' || Array.isArray(row)) throw new Error('Expected evidence row object');
    const source_key = blank(row.source_key) ? '(missing source_key)' : row.source_key;
    const missing = IMPORTANT_FIELDS.filter((field) => blank(row[field]));
    if (!sources.has(source_key)) sources.set(source_key, {
      source_key, total: 0, incomplete: 0,
      missing: Object.fromEntries(IMPORTANT_FIELDS.map((field) => [field, 0])),
    });
    const summary = sources.get(source_key);
    summary.total++;
    if (missing.length) summary.incomplete++;
    for (const field of missing) summary.missing[field]++;
    return { evidence_id: row.evidence_id, source_key, source_locator: row.source_locator, missing };
  });
  return { rows, sources: [...sources.values()] };
}

export function renderMissingFields(data) {
  const audit = auditMissingFields(data);
  const sourceLink = (key) => {
    const raw = data.sources?.[key]?.url;
    try {
      const url = new URL(raw);
      if (['https:', 'http:'].includes(url.protocol)) return `[${escape(key)}](<${url.href.replaceAll('>', '%3E')}>)`;
    } catch { /* Missing provenance must remain visible in an audit. */ }
    return `${escape(key)} (source URL missing or invalid)`;
  };
  const lines = [
    '# Missing-field audit', '',
    'Generated by `node scripts/missing-fields.mjs` from [data/evidence.json](../data/evidence.json).', '',
    'Primary dataset context: [NASA PSI Data Repository](https://psi.nasa.gov/). This is a stored-field completeness audit of all rows, including drafts; it does not validate scientific claims or establish experimental coverage.', '',
    'Blank means an absent key, null, an empty string, or whitespace-only text. Zero is present. Text such as "not stated" is populated, but does not establish a measured value. Pressure means `pressure_kpa`; flow is audited separately as `flow_speed_cm_s` and `flow_direction`. Source counts are row counts, not independent experiments. Missing source URLs remain explicitly marked.', '',
    `Rows: **${audit.rows.length}**; rows with blanks: **${audit.rows.filter((row) => row.missing.length).length}**.`, '',
    '## Per-source summary', '',
    `| Source | Rows | Rows with blanks | ${IMPORTANT_FIELDS.join(' | ')} |`,
    `|---|---|---|${IMPORTANT_FIELDS.map(() => '---').join('|')}|`,
  ];
  for (const source of audit.sources) lines.push(`| ${sourceLink(source.source_key)} | ${source.total} | ${source.incomplete} | ${IMPORTANT_FIELDS.map((field) => source.missing[field]).join(' | ')} |`);
  lines.push('', '## Every evidence row', '', '| Evidence row | Source | Stored source locator | Blank columns |', '|---|---|---|---|');
  for (const row of audit.rows) lines.push(`| ${blank(row.evidence_id) ? '(missing evidence_id)' : escape(row.evidence_id)} | ${sourceLink(row.source_key)} | ${blank(row.source_locator) ? '(blank)' : escape(row.source_locator)} | ${row.missing.length ? row.missing.join(', ') : 'None'} |`);
  return lines.join('\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const input = process.argv[2] ?? fileURLToPath(new URL('../data/evidence.json', import.meta.url));
    const output = process.argv[3] ?? fileURLToPath(new URL('../docs/missing-fields.md', import.meta.url));
    if (process.argv.length > 4) throw new Error('Usage: node scripts/missing-fields.mjs [input.json] [output.md]');
    await writeFile(output, renderMissingFields(JSON.parse(await readFile(input, 'utf8'))));
  } catch (error) {
    console.error(`Missing-field audit failed: ${error.message}`);
    process.exitCode = 1;
  }
}
