import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { runEvaluation } from './eval-holdout.mjs';
import { answerCategory, parseCsv, summarizeResults } from '../src/ui/accuracy-view.js';

const LABELS = ['BURNED', 'NEAR', 'NE-no-burn', 'NE-incompatible', 'NE-no-data'];
const correct = (score) => ['correct', 'correct-refusal'].includes(score);
const expected = (r) => r.query_type === 'incompatible' ? 'NE-incompatible'
  : r.query_type === 'absent' ? 'NE-no-data'
    : ({ burned: 'BURNED', near: 'NEAR', 'no-burn': 'NE-no-burn' }[r.truth] ?? r.truth);
const cell = (v) => String(v ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/\|/g, '&#124;').replace(/[\r\n]+/g, ' ');
const table = (headers, rows) => [headers, headers.map(() => '---'), ...rows]
  .map((row) => `| ${row.map(cell).join(' | ')} |`).join('\n');
function source(key, locator, sources) {
  const url = sources[key]?.url;
  return url && /^https?:\/\//.test(url)
    ? `[${cell(key).replace(/[\[\]]/g, '')}](<${url.replace(/[<>\s]/g, (c) => encodeURIComponent(c))}>) ${cell(locator)}`
    : `${cell(key || 'Not stated')} (source link unavailable) ${cell(locator)}`;
}

export function renderReport(rows, { sources = {}, evidence = [] } = {}) {
  const byId = new Map(evidence.map((r) => [r.evidence_id, r]));
  const citations = (ids) => String(ids || '').split(/\s+/).filter(Boolean).map((id) => {
    const r = byId.get(id);
    return r ? source(r.source_key, id + ': ' + (r.source_locator || ''), sources) : cell(id);
  }).join('; ') || 'None';
  const summary = summarizeResults(rows);
  const test = rows.filter((r) => r.split === 'test');
  const meta = rows[0] ?? {};
  const lines = ['# Holdout evaluation report', '', `Status: **${summary.status}**.`, '',
    `Evaluation: ${cell(meta.evaluation)}; seed: ${cell(meta.run_seed)}; code: ${cell(meta.run_commit)}; run: ${cell(meta.run_at)}.`,
    `Evidence: ${cell(meta.evidence_built_from)} (${cell(meta.evidence_kind)}).`, '',
    'Generated by REDLINE from the existing leave-one-source-out evaluator. Primary NASA dataset: [PSI Data Repository](https://psi.nasa.gov/).', '',
    `${test.length} test queries; ${rows.filter((r) => r.split === 'dev').length} dev queries; ${rows.filter((r) => r.split === 'excluded').length} excluded queries.`,
    'Metrics and matrices use only the test split. Accuracy per label means correct / all queries with that expected label; answerable refusals count as incorrect. Correct control refusals count as correct.',
    'Synthetic results check code only. Descriptive results have too few independent tests. Percentages are withheld unless the existing evaluation gates permit them.', '',
    '## Accuracy per label', ''];
  for (const method of ['redline', 'baseline']) {
    const category = (r) => method === 'redline' ? answerCategory(r.redline_answer, r.redline_reason_code) : r.baseline_answer;
    const labels = [...new Set([...LABELS, ...test.map(expected), ...test.map(category)])];
    lines.push(`### ${method === 'redline' ? 'REDLINE' : 'Naive baseline'}`, '', table(['Expected label', 'Correct', 'Total', 'Accuracy'], labels.map((label) => {
      const eligible = test.filter((r) => expected(r) === label);
      const k = eligible.filter((r) => correct(r[method === 'redline' ? 'score' : 'baseline_score'])).length;
      return [label, k, eligible.length, !eligible.length ? 'n/a' : summary.showRates ? `${(100 * k / eligible.length).toFixed(1)}%` : `${k}/${eligible.length} (counts only)`];
    })), '', 'Confusion matrix: rows = expected; columns = predicted (including refusal categories).', '',
    table(['Expected / predicted', ...labels], labels.map((label) => [label, ...labels.map((predicted) => test.filter((r) => expected(r) === label && category(r) === predicted).length)])), '');
  }
  lines.push('## Every wrong answer', '', 'All scored splits are listed below, including dev errors; excluded queries are omitted. Sources identify truth and cited evidence, not independent validation of the model output.', '');
  const wrong = [];
  for (const r of rows.filter((row) => ['test', 'dev'].includes(row.split))) {
    for (const method of ['redline', 'baseline']) {
      const score = r[method === 'redline' ? 'score' : 'baseline_score'];
      if (correct(score)) continue;
      const predicted = method === 'redline' ? answerCategory(r.redline_answer, r.redline_reason_code) : r.baseline_answer;
      wrong.push([r.query_id, r.split, method, r.material_id, r.holdout_group, expected(r), predicted, score,
        source(r.truth_source_key, r.truth_source_locator, sources), citations(r[`${method}_cited_row`])]);
    }
  }
  // Source links are already escaped Markdown, so preserve them in the source column.
  const headers = ['Query', 'Split', 'Method', 'Material', 'Held-out group', 'Expected', 'Predicted', 'Score', 'Truth source / locator', 'Cited evidence IDs'];
  if (wrong.length) {
    lines.push(table(headers, []).concat('\n', wrong.map((r) => `| ${r.map((v, i) => (i === 8 || i === 9) ? v : cell(v)).join(' | ')} |`).join('\n')));
  } else lines.push('No wrong answers in evaluated queries.');
  lines.push('', '## Evaluation checks', '', ...((summary.kills ?? []).map((k) => `- ${k.id}: ${k.state} - ${k.text}`)), '',
    'Label codes are evaluator categories. Truth links and locators above supply provenance for individual cases; control absences are scoped to the sources reviewed. Arithmetic is computed by REDLINE.', '');
  return lines.join('\n');
}

export function main(argv = process.argv.slice(2)) {
  const args = { evidence: 'data/evidence.json', queries: 'research/validation-queries.csv', out: 'docs/eval-report.md', seed: '7' };
  for (let i = 0; i < argv.length; i += 2) {
    const key = argv[i].replace(/^--/, '');
    if (!argv[i].startsWith('--') || !(key in args) || !argv[i + 1]) throw new Error(`Invalid argument: ${argv[i]}`);
    args[key] = argv[i + 1];
  }
  if (!/^\d+$/.test(args.seed) || !Number.isSafeInteger(Number(args.seed))) throw new Error('Seed must be a non-negative safe integer');
  const evidence = JSON.parse(readFileSync(args.evidence, 'utf8'));
  const text = readFileSync(args.queries, 'utf8');
  const queries = args.queries.endsWith('.json') ? JSON.parse(text) : parseCsv(text);
  const verified = (evidence.evidence ?? []).filter((r) => r.review_status === 'verified');
  const rows = runEvaluation({ evidence, queries, seed: Number(args.seed), meta: {
    evaluation: 'leave-one-source-out', run_seed: args.seed,
    run_commit: execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(),
    run_at: new Date().toISOString(), evidence_built_from: evidence.built_from ?? args.evidence,
    evidence_kind: verified.length && verified.every((r) => r.verified_by === 'fixture-only') ? 'fixture' : 'real',
  } });
  writeFileSync(args.out, renderReport(rows, { sources: evidence.sources, evidence: evidence.evidence }));
  console.log(`Wrote ${args.out}: ${rows.length} queries (${summarizeResults(rows).status}).`);
}

