import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCsv } from '../src/schema/csv.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const materials = new Set(['pmma', 'nomex', 'sibal', 'cotton', 'p213']);
// Match the checklist's escaping, but keep each worksheet entry on one short line.
const cell = (value) => String(value ?? '').replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;')
  .replaceAll('|', '&#124;').replaceAll('[', '&#91;').replaceAll(']', '&#93;')
  .replaceAll('*', '&#42;').replaceAll('_', '&#95;').replaceAll('`', '&#96;')
  .replaceAll('\\', '&#92;').replace(/\s+/g, ' ').trim();
const present = (value) => value !== undefined && value !== null && String(value).trim() !== '';
const number = (value) => present(value) && Number.isFinite(Number(value)) ? Number(value) : null;
const withUnit = (value, unit) => present(value) ? `${value} ${unit}` : 'not stated';
const link = (url, label) => /^https?:\/\//i.test(url)
  ? `[${label}](<${url.replace(/[<>\s|]/g, (c) => encodeURIComponent(c))}>)`
  : cell(url || 'not stated');

function priority(row) {
  if (number(row.gravity_g) === 0.16 || /lunar/i.test(`${row.gravity_context} ${row.gravity_regime}`)) return 0;
  // Prefer test O2; calibrated initial O2 is a separately labelled fallback,
  // never an inferred limit. Final readings do not define the starting condition.
  const oxygen = number(row.o2_pct) ?? number(row.o2_initial_calibrated_vol_pct);
  const iss = /\bISS\b/i.test(`${row.facility} ${row.gravity_regime}`);
  return iss && number(row.gravity_g) === 0 && oxygen !== null && oxygen >= 21 && oxygen <= 34 ? 1 : 2;
}

function oxygen(row) {
  const parts = [];
  if (present(row.o2_pct)) parts.push(`${row.o2_pct} %`);
  if (present(row.o2_initial_calibrated_vol_pct)) parts.push(`initial ${row.o2_initial_calibrated_vol_pct} %`);
  if (present(row.o2_final_calibrated_vol_pct)) parts.push(`final ${row.o2_final_calibrated_vol_pct} %`);
  return parts.join('; ') || 'not stated';
}

function citations(row, sources) {
  const url = row.source_url || row.observation_source_url || sources[row.source_key]?.url || row.condition_source_url || '';
  const locator = !row.source_url && row.observation_source_url
    ? row.observation_source_locator || row.source_locator : row.source_locator;
  const result = [{ url, locator }];
  for (const prefix of ['condition', 'observation']) {
    const extra = { url: row[`${prefix}_source_url`], locator: row[`${prefix}_source_locator`] };
    if (!extra.url && !extra.locator) continue;
    const existing = result.find((c) => c.url === extra.url);
    if (existing) {
      if (extra.locator && !existing.locator?.includes(extra.locator)) {
        existing.locator = [existing.locator, extra.locator].filter(present).join('; ');
      }
    } else {
      result.push(extra);
    }
  }
  return result;
}

export async function generateWorksheet({
  input = resolve(root, 'data/evidence.csv'),
  output = resolve(root, 'docs/verification-demo-sheet.md'),
  sources,
} = {}) {
  sources ??= JSON.parse(await readFile(resolve(root, 'data/metadata.json'), 'utf8')).sources;
  const rows = parseCsv((await readFile(input, 'utf8')).replace(/^\uFEFF/, ''))
    .filter((r) => r.review_status === 'draft' && materials.has(r.material_id))
    .sort((a, b) => priority(a) - priority(b)); // Stable CSV order within each tier.
  const lines = [
    '# Demo-material verification worksheet', '',
    'Generated by `node scripts/verification-worksheet.mjs` from [evidence.csv](../data/evidence.csv).', '',
    'Draft claims only. Check each cited source, exact sample, conditions, endpoint and locator before ticking and signing. This sheet changes no review status and verifies nothing. Regeneration clears ticks and signatures; save completed reviews separately.', '',
    'Primary dataset: [NASA PSI Data Repository](https://psi.nasa.gov/).', '',
    `${rows.length} draft rows: pmma, nomex, sibal, cotton, p213. Order: lunar / 0.16 g; ISS 0 g at 21–34% O2 (test or calibrated initial reading); remaining rows. This order is a demo-review priority, not a scientific ranking.`, '',
    '| ID | Material | O2 | Pressure | Gravity | Claimed outcome (draft) | Source | Page / locator | Checked | Verified by / date |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  const caveats = new Map();
  for (const row of rows) {
    const refs = citations(row, sources);
    const result = [row.endpoint, [row.value_qualifier, row.value, row.value_unit].filter(present).join(' '),
      row.outcome, row.observation_paraphrase].filter(present).join('; ') || 'not stated';
    lines.push(`| ${cell(row.evidence_id)} | ${cell(row.material_id)} | ${cell(oxygen(row))} | ${cell(withUnit(row.pressure_kpa, 'kPa'))} | ${cell(withUnit(row.gravity_g, 'g'))} | ${cell(result)} | ${refs.map((r, i) => link(r.url, `S${i + 1}`)).join(' ')} | ${refs.map((r, i) => `S${i + 1}: ${cell(r.locator || 'not stated')}`).join('; ')} | [ ] |  |`);
    for (const text of [row.caveat, row.gravity_context, present(row.uncertainty) && row.uncertainty !== 'not stated' ? `Uncertainty: ${row.uncertainty}` : '']) {
      if (!present(text)) continue;
      if (!caveats.has(text)) caveats.set(text, []);
      caveats.get(text).push(row.evidence_id);
    }
  }
  if (!rows.length) lines.push('', 'No draft evidence rows for the demo materials.');
  lines.push('', '## Caveats', '',
    '- Unknown values are not zero. Initial/final calibrated O2 readings are not oxygen extinction limits.',
    '- Material IDs group forms and grades. Check full material names, geometry, airflow, extraction notes and endpoint definitions in the linked CSV and cited sources; these are omitted from the compact table.',
    '- Simulated lunar acceleration is not an on-Moon observation. Any lunar behavior estimate must be clearly labelled and bounded by 0 g and 1 g results; do not treat a limit or ignition result as a spread test.');
  for (const [text, ids] of caveats) lines.push(`- ${ids.map(cell).join(', ')}: ${cell(text)}`);
  lines.push('');
  await writeFile(output, lines.join('\n'), 'utf8');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 2) { console.error('Usage: node scripts/verification-worksheet.mjs'); process.exitCode = 1; }
  else try { await generateWorksheet(); console.log('Wrote docs/verification-demo-sheet.md'); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
