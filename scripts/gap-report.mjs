import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Reporting bins, not engine comparability thresholds (S1/S4).
export const ATMOSPHERES = [
  { label: '8.2 psia / 34% O2', pressure: 56.5, oxygen: 34 },
  { label: '10.2 psia / 26.5% O2', pressure: 70.3, oxygen: 26.5 },
  { label: '14.7 psia / 21% O2', pressure: 101.3, oxygen: 21 },
];
const GRAVITIES = ['0 g', 'lunar (simulated)', '1 g'];
const atmosphereSource = 'https://www.nasa.gov/wp-content/uploads/2023/03/abercromby-8.2-34-atm-2015.pdf';
const text = (value) => String(value).replace(/[\r\n]+/g, ' ').replaceAll('|', '&#124;').replace(/[\\`*_[\]<>]/g, '\\$&');
const near = (value, target, tolerance) => typeof value === 'number' && Number.isFinite(value) && Math.abs(value - target) <= tolerance + 1e-9;

export function buildGapMatrix(data) {
  if (!Array.isArray(data.materials) || !Array.isArray(data.evidence)) {
    throw new Error('Expected S1 materials and evidence arrays');
  }
  const materials = data.materials.map((material) => ({ ...material,
    cells: ATMOSPHERES.map(() => GRAVITIES.map(() => [])), rows: [],
  }));
  const byId = new Map(materials.map((material) => [material.material_id, material]));
  if (byId.size !== materials.length) throw new Error('Duplicate material_id');
  const unmatched = [];
  for (const row of data.evidence) {
    const material = byId.get(row.material_id);
    if (!material) throw new Error(`Unknown material_id: ${row.material_id}`);
    material.rows.push(row);
    const atmosphere = ATMOSPHERES.findIndex((a) => near(row.pressure_kpa, a.pressure, 0.1) && near(row.o2_pct, a.oxygen, 0.01));
    const gravity = near(row.gravity_g, 0, 0.01) ? 0
      : near(row.gravity_g, 0.16, 0.01) ? 1
        : near(row.gravity_g, 1, 0.01) ? 2 : -1;
    if (atmosphere < 0 || gravity < 0) unmatched.push(row);
    else material.cells[atmosphere][gravity].push(row);
  }
  return { materials, unmatched };
}

export function renderGapReport(data) {
  const { materials, unmatched } = buildGapMatrix(data);
  const lines = [
    '# Evidence gap report', '',
    'Generated by `node scripts/gap-report.mjs` from [data/evidence.json](../data/evidence.json).', '',
    'Scope: stored rows, including drafts and reviewed rows. Each cell shows **total / verified** rows; EMPTY means no matching row was found in the sources reviewed in this dataset. Counts are inventory, not experimental independence or an engine label.', '',
    'Atmosphere bins require both pressure and oxygen: pressure within 0.1 kPa of 56.5, 70.3 or 101.3 kPa and oxygen within 0.01 percentage point of the heading. These are reporting tolerances for rounding, not physical comparability rules. Unknown values do not match.', '',
    `[Atmosphere source: NASA, Table 1, journal p. 77 / PDF p. 2](${atmosphereSource}). Presets are dated comparison settings, not vehicle requirements.`, '',
    'Gravity bins are within 0.01 g of 0, 0.16 (including 1/6 g), and 1. Other partial gravities are excluded. Lunar counts describe simulated-lunar records, not lunar-surface measurements; no interpolation or estimated rows are added. [NASA simulated-gravity context, methods pp. 5-8](https://ntrs.nasa.gov/api/citations/20250002114/downloads/ICES_2025-392-correctedcaptions.pdf).', '',
    'Primary dataset context: [NASA PSI Data Repository](https://psi.nasa.gov/). Row-level source links and locators appear in the inventory below. Materials without records are catalog entries, not sourced experimental findings.', '',
    '| Material | ' + ATMOSPHERES.flatMap((a) => GRAVITIES.map((g) => `[${a.label}](${atmosphereSource})  /  ${g}`)).join(' | ') + ' |',
    '|---|' + Array(9).fill('---').join('|') + '|',
  ];
  let empty = 0;
  materials.forEach((material, index) => {
    const cells = material.cells.flat().map((rows) => {
      if (rows.length === 0) { empty++; return '0 / 0 **EMPTY**'; }
      return `[${rows.length} / ${rows.filter((r) => r.review_status === 'verified').length}](#material-${index + 1})`;
    });
    lines.push(`| [${text(material.display_name)}](#material-${index + 1}) | ${cells.join(' | ')} |`);
  });
  lines.push('', `Empty cells: **${empty} of ${materials.length * 9}**. Rows outside the matrix (other conditions or unknown fields): **${unmatched.length} of ${data.evidence.length}**.`, '', '## Source inventory', '');
  materials.forEach((material, index) => {
    lines.push(`<a id="material-${index + 1}"></a>`, '', `### ${text(material.display_name)} (${text(material.material_id)})`, '');
    if (!material.rows.length) lines.push('Not found in the sources reviewed in this dataset.', '');
    for (const row of material.rows) {
      const source = data.sources?.[row.source_key];
      if (!source?.url || !row.source_locator) throw new Error(`Missing source URL or locator: ${row.evidence_id}`);
      const url = new URL(source.url);
      if (!['https:', 'http:'].includes(url.protocol)) throw new Error(`Invalid source URL: ${row.evidence_id}`);
      const conditions = `O2 ${row.o2_pct ?? 'unknown'}%; pressure ${row.pressure_kpa ?? 'unknown'} kPa; gravity ${row.gravity_g ?? 'unknown'} g`;
      lines.push(`- ${text(row.evidence_id)}  -  ${text(row.review_status)}; ${text(conditions)}; ${unmatched.includes(row) ? 'outside matrix' : 'in matrix'}. [${text(source.title || row.source_key)}](<${url.href.replaceAll('>', '%3E')}>)  -  ${text(row.source_locator)}.`);
    }
    lines.push('');
  });
  return lines.join('\n');
}

export async function writeGapReport(input = new URL('../data/evidence.json', import.meta.url), output = new URL('../docs/gap-report.md', import.meta.url)) {
  const report = renderGapReport(JSON.parse(await readFile(input, 'utf8')));
  await mkdir(dirname(output instanceof URL ? fileURLToPath(output) : output), { recursive: true });
  await writeFile(output, report, 'utf8');
  return report;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    await writeGapReport(...process.argv.slice(2));
  } catch (error) {
    console.error(`Gap report failed: ${error.message}`);
    process.exitCode = 1;
  }
}
